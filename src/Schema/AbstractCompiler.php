declare(strict_types=1);

namespace Puff\Migration\Schema;

use Puff\Migration\Blueprint;
use Puff\Migration\Column;
use Puff\Migration\Exception\UnsupportedSchemaOperation;
use Puff\Migration\ForeignKey;
use Puff\Migration\Index;

abstract class AbstractCompiler implements CompilerInterface
{
    public function __construct(private readonly string $prefix = '')
    {
        if ($prefix !== '' && \preg_match('/^[A-Za-z0-9_]+$/D', $prefix) !== 1) {
            throw new \InvalidArgumentException("Invalid schema table prefix [{$prefix}].");
        }
    }

    public function create(Blueprint $blueprint): array
    {
        $definitions = \array_map($this->column(...), $blueprint->columns());
        foreach ($blueprint->foreignKeys() as $foreignKey) {
            $definitions[] = $this->foreign($blueprint->table, $foreignKey);
        }
        if ($definitions === []) {
            throw new \InvalidArgumentException('A table must define at least one column.');
        }
        $sql = [\sprintf(
            'CREATE TABLE %s (%s)',
            $this->quote($this->table($blueprint->table)),
            \implode(', ', $definitions),
        )];
        foreach ($this->indexes($blueprint) as $index) {
            $sql[] = $this->createIndex($blueprint->table, $index);
        }
        return $sql;
    }

    public function alter(Blueprint $blueprint): array
    {
        $sql = [];
        foreach ($blueprint->columns() as $column) {
            $sql[] = \sprintf(
                'ALTER TABLE %s ADD COLUMN %s',
                $this->quote($this->table($blueprint->table)),
                $this->column($column),
            );
        }
        foreach ($blueprint->droppedColumns() as $column) {
            $sql[] = \sprintf(
                'ALTER TABLE %s DROP COLUMN %s',
                $this->quote($this->table($blueprint->table)),
                $this->quote($column),
            );
        }
        foreach ($blueprint->renamedColumns() as $rename) {
            $sql[] = \sprintf(
                'ALTER TABLE %s RENAME COLUMN %s TO %s',
                $this->quote($this->table($blueprint->table)),
                $this->quote($rename['from']),
                $this->quote($rename['to']),
            );
        }
        foreach ($this->indexes($blueprint) as $index) {
            $sql[] = $index->drop
                ? $this->dropIndex($blueprint->table, $index)
                : $this->createIndex($blueprint->table, $index);
        }
        foreach ($blueprint->foreignKeys() as $foreignKey) {
            $sql[] = \sprintf(
                'ALTER TABLE %s ADD %s',
                $this->quote($this->table($blueprint->table)),
                $this->foreign($blueprint->table, $foreignKey),
            );
        }
        return $sql;
    }

    public function rename(string $from, string $to): string
    {
        return \sprintf('ALTER TABLE %s RENAME TO %s', $this->quote($this->table($from)), $this->quote($this->table($to)));
    }

    public function drop(string $table, bool $ifExists = false): string
    {
        return 'DROP TABLE ' . ($ifExists ? 'IF EXISTS ' : '') . $this->quote($this->table($table));
    }

    protected function quote(string $identifier): string
    {
        Identifier::validate($identifier);
        return $this->quoteCharacter() . $identifier . $this->quoteCharacter();
    }

    protected function column(Column $column): string
    {
        $sql = $this->quote($column->name) . ' ' . $this->type($column);
        if ($column->unsigned && $this->supportsUnsigned()) {
            $sql .= ' UNSIGNED';
        }
        if (!$column->nullable) {
            $sql .= ' NOT NULL';
        }
        if ($column->hasDefault) {
            $sql .= ' DEFAULT ' . $this->defaultValue($column->default);
        }
        if ($column->primary) {
            $sql .= ' PRIMARY KEY';
        }
        return $sql . $this->autoIncrement($column);
    }

    protected function type(Column $column): string
    {
        return match ($column->type) {
            'integer' => 'INTEGER',
            'bigInteger' => 'BIGINT',
            'string' => 'VARCHAR(' . ($column->length ?? 255) . ')',
            'text' => 'TEXT',
            'boolean' => 'BOOLEAN',
            'decimal' => 'DECIMAL(' . ($column->length ?? 10) . ', ' . ($column->scale ?? 2) . ')',
            'date' => 'DATE',
            'dateTime' => 'DATETIME',
            'timestamp' => 'TIMESTAMP',
            'json' => 'JSON',
            'binary' => 'BLOB',
            default => throw new UnsupportedSchemaOperation("Unsupported column type [{$column->type}]."),
        };
    }

    protected function autoIncrement(Column $column): string
    {
        return $column->autoIncrement ? ' GENERATED BY DEFAULT AS IDENTITY' : '';
    }

    protected function supportsUnsigned(): bool
    {
        return false;
    }

    protected function defaultValue(mixed $value): string
    {
        return match (true) {
            $value === null => 'NULL',
            \is_bool($value) => $value ? '1' : '0',
            \is_int($value) => (string) $value,
            \is_float($value) && \is_finite($value) => (string) $value,
            \is_string($value) => "'" . \str_replace("'", "''", $value) . "'",
            default => throw new \InvalidArgumentException('Column default value is invalid.'),
        };
    }

    protected function foreign(string $table, ForeignKey $foreignKey): string
    {
        if ($foreignKey->referencedTable === null || $foreignKey->referencedColumn === null) {
            throw new \LogicException("Foreign key [{$foreignKey->column}] must define references() and on().");
        }
        $name = $foreignKey->name ?? $this->name($table, [$foreignKey->column], 'foreign');
        $sql = \sprintf(
            'CONSTRAINT %s FOREIGN KEY (%s) REFERENCES %s (%s)',
            $this->quote($name),
            $this->quote($foreignKey->column),
            $this->quote($this->table($foreignKey->referencedTable)),
            $this->quote($foreignKey->referencedColumn),
        );
        if ($foreignKey->deleteAction !== null) {
            $sql .= ' ON DELETE ' . $foreignKey->deleteAction;
        }
        if ($foreignKey->updateAction !== null) {
            $sql .= ' ON UPDATE ' . $foreignKey->updateAction;
        }
        return $sql;
    }

    protected function createIndex(string $table, Index $index): string
    {
        $name = $index->name ?? $this->name($table, $index->columns, $index->unique ? 'unique' : 'index');
        return \sprintf(
            'CREATE %sINDEX %s ON %s (%s)',
            $index->unique ? 'UNIQUE ' : '',
            $this->quote($name),
            $this->quote($this->table($table)),
            \implode(', ', \array_map($this->quote(...), $index->columns)),
        );
    }

    protected function dropIndex(string $table, Index $index): string
    {
        $name = $index->name ?? throw new \LogicException('Dropped index must define its name.');
        return 'DROP INDEX ' . $this->quote($name);
    }

    /** @return list<Index> */
    private function indexes(Blueprint $blueprint): array
    {
        $indexes = $blueprint->indexes();
        foreach ($blueprint->columns() as $column) {
            if ($column->unique) {
                $indexes[] = new Index([$column->name], true);
            } elseif ($column->indexed) {
                $indexes[] = new Index([$column->name]);
            }
        }
        return $indexes;
    }

    /** @param list<string> $columns */
    private function name(string $table, array $columns, string $suffix): string
    {
        $name = \strtolower($this->table($table) . '_' . \implode('_', $columns) . '_' . $suffix);
        return Identifier::validate(\strlen($name) <= 63 ? $name : \substr($name, 0, 54) . '_' . \substr(\hash('sha256', $name), 0, 8));
    }

    protected function table(string $table): string
    {
        return $this->prefix . Identifier::validate($table);
    }

    abstract protected function quoteCharacter(): string;
}
